/**
 * Metadata definition describing a relationship (link) between two OAObject
 * types. OALinkInfo specifies the cardinality (ONE or MANY), the reverse link
 * name, foreign key mapping, and behavioral rules for maintaining referential
 * integrity in the OA Object Graph.
 *
 * <p>Link metadata is generated by OABuilder from the application model and is
 * used throughout the OA runtime to enforce automatic bidirectional
 * consistency, lazy loading, and cascade behavior without requiring manual
 * coding by the application developer.</p>
 *
 * <p>An OALinkInfo instance always defines one side of a relationship. When a
 * reverse link exists, both sides are registered so that changes are
 * automatically reflected on the opposite side:</p>
 *
 * <ul>
 *   <li>ONE ↔ MANY (e.g., Department → Employees)</li>
 *   <li>ONE ↔ ONE (unique pairing)</li>
 *   <li>MANY ↔ MANY (Hub on both sides)</li>
 * </ul>
 *
 * <p>At runtime, this metadata drives:</p>
 *
 * <ul>
 *   <li>Reverse link creation and updates</li>
 *   <li>Foreign key assignment and reconciliation</li>
 *   <li>Lazy loading via OAObjectKey references</li>
 *   <li>Cascade rules for delete and referenceability</li>
 *   <li>Hub population for collections</li>
 * </ul>
 *
 * @see OAObjectInfo
 * @see OAObjectPropertyDelegate
 * @see Hub
 */
