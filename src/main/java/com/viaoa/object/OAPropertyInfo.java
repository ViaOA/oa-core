/**
 * Metadata describing a property of an OAObject type. OAPropertyInfo defines
 * the name, Java type, and behavioral rules for how a value is stored,
 * validated, edited, loaded, and persisted within the OA Object Graph.
 *
 * <p>This metadata is generated by OABuilder from the application model and is
 * used throughout the runtime to enable dynamic behavior such as lazy loading,
 * UI data binding, business rule execution, and database mapping. No static
 * configuration or boilerplate is required in the application code.</p>
 *
 * <p>Property metadata includes:</p>
 * <ul>
 *   <li>Java type and nullability</li>
 *   <li>Getter and setter methods</li>
 *   <li>Persistence and update flags</li>
 *   <li>Editable and display rules</li>
 *   <li>Converter usage for formatting and serialization</li>
 * </ul>
 *
 * <p>OAPropertyInfo instances are immutable after construction and are
 * accessed through OAObjectInfo for fast runtime lookup.</p>
 *
 * @see OAObjectInfo
 * @see OAObject
 * @see OALinkInfo
 */
